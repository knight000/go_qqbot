// Command genplugins 扫描 plugins/ 下的插件目录，生成 cmd/bot/plugins_gen.go。
//
// Go 的 import 是静态的，编译器不会去"发现"目录里的包，所以"放入即生效"只能
// 靠生成这一步。生成的是一行行 blank import，插件仍然在 init() 里注册。
//
// 用法（在 cmd/bot 下由 go:generate 调起，也可以手动跑）：
//
//	go run ./tools/genplugins
//
// 生成文件不入库：核心仓克隆下来即可构建（main.go 里有示例插件），
// 插件工作区跑一次生成就把新插件编进来。
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const modulePath = "github.com/knight000/go_qqbot"

func main() {
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}

	names, err := pluginDirs(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genplugins; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	if len(names) == 0 {
		b.WriteString("// plugins/ 下没有可用插件。\n")
	} else {
		b.WriteString("import (\n")
		for _, n := range names {
			fmt.Fprintf(&b, "\t_ %q\n", modulePath+"/plugins/"+n)
		}
		b.WriteString(")\n")
	}

	out := filepath.Join(root, "cmd", "bot", "plugins_gen.go")
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}
	fmt.Printf("genplugins: %d 个插件 -> %s\n", len(names), filepath.ToSlash(out))
}

// moduleRoot 从当前目录向上找 go.mod。go:generate 的工作目录是包目录，
// 所以不能假设 cwd 就是仓库根。
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("找不到 go.mod（从 %s 向上）", dir)
		}
		dir = parent
	}
}

// pluginDirs 返回 plugins/ 下所有"能真正注册"的插件目录名，按字典序。
//
// 判据不是"目录里有 package"，而是"该目录（含一层子包）出现过 host.Register("。
// 两者不等价：插件代码放在 plugins/foo/plugin/ 里、根目录只剩一个不 import 它的
// 空包，或者目录其实是共享库时，blank import 照样能编译通过，但 host.Registered()
// 里永远不会有它——现场表现是"构建全绿、指令没反应"（P3-19）。
//
// 一层子包是必须的：插件仓的根包只做 blank import 转发（ARCHITECTURE §3.5）
// 是合法形态，注册调用在子包里。
func pluginDirs(root string) ([]string, error) {
	base := filepath.Join(root, "plugins")
	entries, err := os.ReadDir(base)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		name := e.Name()
		if skipEntry(name) {
			continue
		}
		dir := filepath.Join(base, name)
		rootSrc, err := hasGoSource(dir)
		if err != nil {
			return nil, err
		}
		registered, err := hasRegisterCall(dir, 1)
		if err != nil {
			return nil, err
		}
		switch {
		case rootSrc && registered:
			names = append(names, name)
		case rootSrc:
			return nil, fmt.Errorf("plugins/%s: 目录里有 Go 源码，但（含一层子包）找不到 host.Register(——它不会被注册", name)
		case registered:
			return nil, fmt.Errorf("plugins/%s: 注册代码只在子包里，根包没有 Go 源文件；按约定根包应 blank import 子包", name)
		default:
			// 既没有根包源码、也没有注册调用：不是插件（文档、共享资源目录），跳过。
		}
	}
	sort.Strings(names)
	return names, nil
}

// hasRegisterCall 报告 dir 及其 depth 层子包里是否出现过 host.Register(。
//
// 只做文本匹配：目的不是判断代码是否合法，而是挡住"目录里有包就当成插件"
// 这个更宽松、也更危险的判据。注册调用写在注释里会被误判为通过，代价可以接受。
func hasRegisterCall(dir string, depth int) (bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() {
			if depth <= 0 || skipEntry(name) {
				continue
			}
			ok, err := hasRegisterCall(filepath.Join(dir, name), depth-1)
			if err != nil || ok {
				return ok, err
			}
			continue
		}
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return false, err
		}
		if bytes.Contains(data, []byte("host.Register(")) {
			return true, nil
		}
	}
	return false, nil
}

// skipEntry 跳过编辑器/工具目录与 Go 约定忽略的 "_" 前缀目录。
func skipEntry(name string) bool {
	return strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_")
}

func hasGoSource(dir string) (bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return false, err
		}
		if isPackageClause(data) {
			return true, nil
		}
	}
	return false, nil
}

func isPackageClause(src []byte) bool {
	for _, line := range strings.Split(string(src), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "//") || strings.HasPrefix(line, "/*") || strings.HasPrefix(line, "*") {
			continue
		}
		return strings.HasPrefix(line, "package ")
	}
	return false
}
