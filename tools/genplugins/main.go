// Command genplugins 扫描 plugins/ 下的插件目录，生成 cmd/bot/plugins_gen.go。
//
// Go 的 import 是静态的，编译器不会去"发现"目录里的包，所以"放入即生效"只能
// 靠生成这一步。生成的是一行行 blank import，插件仍然在 init() 里注册。
//
// 用法（在 cmd/bot 下由 go:generate 调起，也可以手动跑）：
//
//	go run ./tools/genplugins
//
// 生成文件不入库：核心仓克隆下来即可构建（main.go 里有示例插件），
// 插件工作区跑一次生成就把新插件编进来。
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const modulePath = "github.com/knight000/go_qqbot"

func main() {
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}

	names, err := pluginDirs(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genplugins; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	if len(names) == 0 {
		b.WriteString("// plugins/ 下没有可用插件。\n")
	} else {
		b.WriteString("import (\n")
		for _, n := range names {
			fmt.Fprintf(&b, "\t_ %q\n", modulePath+"/plugins/"+n)
		}
		b.WriteString(")\n")
	}

	out := filepath.Join(root, "cmd", "bot", "plugins_gen.go")
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}
	fmt.Printf("genplugins: %d 个插件 -> %s\n", len(names), filepath.ToSlash(out))
}

// moduleRoot 从当前目录向上找 go.mod。go:generate 的工作目录是包目录，
// 所以不能假设 cwd 就是仓库根。
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("找不到 go.mod（从 %s 向上）", dir)
		}
		dir = parent
	}
}

// pluginDirs 返回 plugins/ 下所有含非测试 Go 源码的目录名，按字典序。
//
// 只认直接子目录：插件的内部包（如 plugins/foo/api）由插件自己 import，
// 不能在这里重复引导。
func pluginDirs(root string) ([]string, error) {
	base := filepath.Join(root, "plugins")
	entries, err := os.ReadDir(base)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		name := e.Name()
		if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
			continue
		}
		ok, err := hasGoSource(filepath.Join(base, name))
		if err != nil {
			return nil, err
		}
		if ok {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names, nil
}

func hasGoSource(dir string) (bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return false, err
		}
		if isPackageClause(data) {
			return true, nil
		}
	}
	return false, nil
}

func isPackageClause(src []byte) bool {
	for _, line := range strings.Split(string(src), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "//") || strings.HasPrefix(line, "/*") || strings.HasPrefix(line, "*") {
			continue
		}
		return strings.HasPrefix(line, "package ")
	}
	return false
}
