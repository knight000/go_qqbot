package main

import (
	"fmt"
	"strings"
)

// emitData 是渲染产物所需的全部输入。
//
// 刻意不含时间戳：产物要能逐字比对（`-check`、CI、code review 里的 diff）。
// 带一个「生成于某时」的注释，每次重跑都会产生一个无意义的 diff，久而久之
// 没人再看这个文件的变化——而它的变化恰恰是「插件开始依赖新成员」的信号。
type emitData struct {
	Module    string // 插件 module 路径，只用于头注释
	PkgName   string
	TypeName  string
	Pointer   bool
	Members   []string
	Contract  origin
	Generator string // 生成器自身的版本（v0.0.1 / (devel)）
}

// generatorPrefix 是产物头里「生成器版本」那一行的前缀。
//
// 单独成常量是因为它有两个用途：渲染时写进去，`-check` 比对时抹掉（见
// stripGeneratorLine）。两处写死字符串迟早漂移，而漂移的表现是「比对永远不等」。
const generatorPrefix = "// 生成器："

// render 把使用面渲染成 Go 源码。
func render(d emitData) []byte {
	var b strings.Builder

	b.WriteString("// Code generated by tools/apisurface; DO NOT EDIT.\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// 本文件是 %s 的「使用面」：它静态引用到的契约成员，粒度到成员\n", d.Module)
	b.WriteString("// （\"Event.Args\" 这一级，不是 \"host.Event\"）。由 pkg/rpc 在清单出口并入\n")
	b.WriteString("// Manifest.Uses，核心据此判定兼容（ADR-0007）。\n")
	b.WriteString("//\n")
	b.WriteString("// 生成方式（在插件 module 根目录，<pin> 取 go.mod 里核心仓的版本）：\n")
	b.WriteString("//\n")
	b.WriteString("//\tgo run github.com/knight000/go_qqbot/tools/apisurface@<pin>\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// 契约包：%s\n", d.Contract)
	b.WriteString(generatorPrefix)
	b.WriteString(d.Generator)
	b.WriteString("\n")
	b.WriteString("//\n")
	b.WriteString("// 反射里才用到的成员静态扫描看不见：写进 uses_extra.go，由 Manifest.Uses\n")
	b.WriteString("// 带上，与本文件取并集（重复项去重）。改了插件代码就重跑生成——漏跑不会\n")
	b.WriteString("// 报错，只会让使用面停在旧的那一份，而判定读的就是它。\n")
	b.WriteString("\n")

	fmt.Fprintf(&b, "package %s\n", d.PkgName)
	b.WriteString("\n")
	b.WriteString("// APISurface 返回本插件静态引用到的契约成员（成员级）。\n")
	b.WriteString("// 由 pkg/rpc 并入 Manifest.Uses：与手写追加项取并集、去重、排序。\n")

	recv := d.TypeName
	if d.Pointer {
		recv = "*" + d.TypeName
	}
	fmt.Fprintf(&b, "func (p %s) APISurface() []string {\n", recv)
	b.WriteString("\treturn []string{\n")
	for _, m := range d.Members {
		fmt.Fprintf(&b, "\t\t%q,\n", m)
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n")

	return []byte(b.String())
}

// stripGeneratorLine 返回抹掉「生成器」那一行之后的源码。
//
// 只给 `-check` 用。这一行记录的是**这次生成用的生成器从哪来**（`@v0.0.2`
// 还是工作区），随调用方式变、不随插件代码变；内容比对要对「怎么跑的」宽容，
// 对「扫出了什么」严格。同源检查有 sameOrigin 专门管，不靠这一行。
func stripGeneratorLine(src []byte) []byte {
	lines := strings.Split(string(src), "\n")
	out := make([]string, 0, len(lines))
	for _, line := range lines {
		if strings.HasPrefix(line, generatorPrefix) {
			continue
		}
		out = append(out, line)
	}
	return []byte(strings.Join(out, "\n"))
}
