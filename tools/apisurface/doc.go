// Command apisurface 生成插件的「使用面」——它对契约成员的真实引用集合。
//
// 在插件 module 里跑一条命令，产物落到插件类型所在包：
//
//	go run github.com/knight000/go_qqbot/tools/apisurface@<pin>
//
// 产物是一个挂在该插件类型上的方法（`func (p *Plugin) APISurface() []string`），
// 由 pkg/rpc 在清单出口并入 `Manifest.Uses`，核心据此判定兼容（ADR-0007）。
//
// # 为什么必须生成，不能手写
//
// 使用面是**判定输入**：核心取 `(插件编译时的契约版本, 核心版本]` 区间里的
// 非增量变更，与使用面求交，相交即拒载。漏一条就等于给一个真实的不兼容变更
// 开后门，而症状是「加载成功、行为悄悄变了」——比拒载难查得多。一个两万行的
// 插件有五十来条引用，手写必漏。
//
// # 为什么住在核心仓、用 @pin 调用
//
// 生成器必须理解它扫描的那个契约版本（成员怎么组织、哪些是字段、哪些是方法）。
// 插件的 pin 是唯一权威：`@<pin>` 让生成器与契约版本同源。复制进插件仓会与 pin
// 漂移，而漂移没有任何检查能发现——所以本工具还会比对「自己的版本」与「插件
// module 里解析出的契约包版本」，不一致直接失败（ADR-0007 决策 4）。
//
// # 扫描粒度与边界
//
// 粒度到成员：`Event.Args`、`Params.Duration`、`JobSpec`。依据是 go/types 的
// 对象解析，不是文本匹配——类型别名会被还原到契约包里的原始类型，泛型实参与
// 嵌入接口取到的是真正声明那个成员的类型。
//
// 抓不到的两类，各有对策：
//   - 反射调用（`reflect.Value.FieldByName("Args")`）：静态扫描看不见，写进
//     `uses_extra.go` 并由 `Manifest.Uses` 带上，与本产物取并集、去重；
//   - 插件自己的测试文件：不扫（`Tests: false`）。测试不是产物的一部分，
//     把它们算进使用面只会让插件因为测试代码而被拒载。
//
// 产物文件本身不参与扫描：它是纯数据（只有字符串字面量），本来就没有契约引用，
// 跳过是为了在有人手改它、往里加 `host.X` 时仍然幂等。
